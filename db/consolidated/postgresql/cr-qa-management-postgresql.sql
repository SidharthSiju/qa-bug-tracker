-- Creates the whole current schema (27 tables, 14 sequences, indexes and constraints) and the seed data the
-- application expects, in one script that can be run against an empty database. It replaces the migration chain
-- (classpath:db/postgresql, V1..V26) for a NEW environment; existing environments keep their Flyway history and are
-- untouched by this file.
--
-- It was generated from a database built by those very migrations, so it is the migration chain's own result.
--
-- Usage:
--     createdb crqa
--     psql -d crqa -f cr-qa-management-postgresql.sql
--
-- Then point the application at that database. Flyway must NOT replay the migrations on a database this script
-- created, so run it once with:
--     SPRING_FLYWAY_BASELINE_ON_MIGRATE=true SPRING_FLYWAY_BASELINE_VERSION=26
-- (or, in application.yml: spring.flyway.baseline-on-migrate=true, baseline-version=26). Flyway then records the
-- database as already being at V26 and applies only migrations newer than that.
--
-- Why the sequences come first: the chain's seed inserts (V2/V3/V5/V6) call nextval('IT_users_seq') and friends,
-- but the chain only creates those sequences later (V15), so a fresh PostgreSQL database could never finish the
-- chain. Here every object is created before any row is inserted, which removes that ordering trap. On PostgreSQL
-- the names are case-folded to lower case, which is what both those inserts and Hibernate's
-- @SequenceGenerator(sequenceName = "IT_USERS_SEQ") resolve to; do not "fix" the case.
--
-- Generated from the migration chain at 5389e01, PostgreSQL dump format, no ownership or privileges.
