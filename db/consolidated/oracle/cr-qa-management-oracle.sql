DECLARE
    v_name VARCHAR2(128);
BEGIN
    SELECT uc.constraint_name INTO v_name
    FROM user_constraints uc
    JOIN user_cons_columns ucc
      ON ucc.constraint_name = uc.constraint_name
     AND ucc.table_name = uc.table_name
    WHERE uc.table_name = 'CHANGE_REQUEST'
      AND uc.constraint_type = 'U'
    GROUP BY uc.constraint_name
    HAVING COUNT(*) = 1 AND MAX(ucc.column_name) = 'CR_NUMBER';

    EXECUTE IMMEDIATE 'ALTER TABLE change_request DROP CONSTRAINT "' || v_name || '"';
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END;
/

