-- Run these scripts connected as the CRQA application schema/user.
-- Oracle does not support CREATE SCHEMA IF NOT EXISTS, so the schema must
-- be provisioned by the DBA before running this migration.
CREATE TABLE users (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100 CHAR) NOT NULL UNIQUE,
    display_name VARCHAR2(200 CHAR) NOT NULL,
    email VARCHAR2(255 CHAR),
    password VARCHAR2(100 CHAR) NOT NULL,
    active NUMBER(1,0) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE user_roles (
    user_id NUMBER(19,0) NOT NULL,
    role VARCHAR2(50 CHAR) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE project (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    project_name VARCHAR2(200 CHAR) NOT NULL,
    description VARCHAR2(4000 CHAR),
    active NUMBER(1,0) DEFAULT 1 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE change_request (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cr_number VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    cr_name VARCHAR2(255 CHAR) NOT NULL,
    description VARCHAR2(4000 CHAR),
    project_id NUMBER(19,0),
    environment VARCHAR2(50 CHAR),
    priority VARCHAR2(30 CHAR),
    complexity VARCHAR2(30 CHAR),
    development_owner_id NUMBER(19,0),
    qa_lead_id NUMBER(19,0),
    sa_id NUMBER(19,0),
    status VARCHAR2(50 CHAR) NOT NULL,
    planned_start_date TIMESTAMP,
    planned_end_date TIMESTAMP,
    actual_start_date TIMESTAMP,
    actual_end_date TIMESTAMP,
    created_by NUMBER(19,0) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_by NUMBER(19,0),
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    version NUMBER(19,0) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_cr_project FOREIGN KEY (project_id) REFERENCES project(id),
    CONSTRAINT fk_cr_dev_owner FOREIGN KEY (development_owner_id) REFERENCES users(id),
    CONSTRAINT fk_cr_qa_lead FOREIGN KEY (qa_lead_id) REFERENCES users(id),
    CONSTRAINT fk_cr_created_by FOREIGN KEY (created_by) REFERENCES users(id),
    CONSTRAINT fk_cr_updated_by FOREIGN KEY (updated_by) REFERENCES users(id)
);

CREATE TABLE cr_activity (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cr_id NUMBER(19,0) NOT NULL,
    activity_type VARCHAR2(50 CHAR),
    description VARCHAR2(4000 CHAR),
    performed_by NUMBER(19,0),
    performed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_cr_activity_cr FOREIGN KEY (cr_id) REFERENCES change_request(id),
    CONSTRAINT fk_cr_activity_user FOREIGN KEY (performed_by) REFERENCES users(id)
);

CREATE TABLE test_cycle (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cr_id NUMBER(19,0) NOT NULL,
    cycle_number NUMBER(10,0) NOT NULL,
    name VARCHAR2(200 CHAR),
    start_date TIMESTAMP,
    end_date TIMESTAMP,
    status VARCHAR2(50 CHAR),
    created_by NUMBER(19,0) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_test_cycle_cr FOREIGN KEY (cr_id) REFERENCES change_request(id),
    CONSTRAINT fk_test_cycle_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE test_case (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_case_number VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    cr_id NUMBER(19,0) NOT NULL,
    cycle_id NUMBER(19,0),
    title VARCHAR2(500 CHAR) NOT NULL,
    description VARCHAR2(4000 CHAR),
    expected_result VARCHAR2(4000 CHAR),
    actual_result VARCHAR2(4000 CHAR),
    status VARCHAR2(30 CHAR),
    executed_by NUMBER(19,0),
    executed_at TIMESTAMP,
    CONSTRAINT fk_test_case_cr FOREIGN KEY (cr_id) REFERENCES change_request(id),
    CONSTRAINT fk_test_case_cycle FOREIGN KEY (cycle_id) REFERENCES test_cycle(id),
    CONSTRAINT fk_test_case_user FOREIGN KEY (executed_by) REFERENCES users(id)
);

CREATE TABLE bug (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bug_number VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    cr_id NUMBER(19,0) NOT NULL,
    test_case_id NUMBER(19,0),
    title VARCHAR2(500 CHAR) NOT NULL,
    description VARCHAR2(4000 CHAR) NOT NULL,
    steps_to_reproduce VARCHAR2(4000 CHAR),
    expected_result VARCHAR2(4000 CHAR),
    actual_result VARCHAR2(4000 CHAR),
    severity VARCHAR2(30 CHAR) NOT NULL,
    priority VARCHAR2(30 CHAR) NOT NULL,
    status VARCHAR2(50 CHAR) NOT NULL,
    environment VARCHAR2(50 CHAR),
    application VARCHAR2(100 CHAR),
    module VARCHAR2(100 CHAR),
    reported_by NUMBER(19,0) NOT NULL,
    assigned_to NUMBER(19,0),
    reported_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    assigned_at TIMESTAMP,
    fixed_at TIMESTAMP,
    retested_at TIMESTAMP,
    closed_at TIMESTAMP,
    resolution VARCHAR2(50 CHAR),
    resolution_comment VARCHAR2(4000 CHAR),
    version NUMBER(19,0) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bug_cr FOREIGN KEY (cr_id) REFERENCES change_request(id),
    CONSTRAINT fk_bug_test_case FOREIGN KEY (test_case_id) REFERENCES test_case(id),
    CONSTRAINT fk_bug_reported_by FOREIGN KEY (reported_by) REFERENCES users(id),
    CONSTRAINT fk_bug_assigned_to FOREIGN KEY (assigned_to) REFERENCES users(id)
);

CREATE TABLE bug_comment (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bug_id NUMBER(19,0) NOT NULL,
    comment_text VARCHAR2(4000 CHAR) NOT NULL,
    comment_type VARCHAR2(50 CHAR),
    created_by NUMBER(19,0) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bug_comment_bug FOREIGN KEY (bug_id) REFERENCES bug(id),
    CONSTRAINT fk_bug_comment_user FOREIGN KEY (created_by) REFERENCES users(id)
);

CREATE TABLE bug_attachment (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bug_id NUMBER(19,0) NOT NULL,
    file_name VARCHAR2(255 CHAR) NOT NULL,
    content_type VARCHAR2(100 CHAR),
    file_size NUMBER(19,0),
    storage_type VARCHAR2(30 CHAR),
    storage_path VARCHAR2(1000 CHAR),
    uploaded_by NUMBER(19,0) NOT NULL,
    uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bug_attachment_bug FOREIGN KEY (bug_id) REFERENCES bug(id),
    CONSTRAINT fk_bug_attachment_user FOREIGN KEY (uploaded_by) REFERENCES users(id)
);

CREATE TABLE bug_history (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bug_id NUMBER(19,0) NOT NULL,
    action VARCHAR2(100 CHAR) NOT NULL,
    old_status VARCHAR2(50 CHAR),
    new_status VARCHAR2(50 CHAR),
    old_assignee NUMBER(19,0),
    new_assignee NUMBER(19,0),
    comment_text VARCHAR2(4000 CHAR),
    performed_by NUMBER(19,0) NOT NULL,
    performed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bug_history_bug FOREIGN KEY (bug_id) REFERENCES bug(id),
    CONSTRAINT fk_bug_history_user FOREIGN KEY (performed_by) REFERENCES users(id)
);

CREATE TABLE notification (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id NUMBER(19,0) NOT NULL,
    type VARCHAR2(50 CHAR),
    subject VARCHAR2(255 CHAR),
    message VARCHAR2(4000 CHAR),
    reference_type VARCHAR2(50 CHAR),
    reference_id NUMBER(19,0),
    read_flag NUMBER(1,0) DEFAULT 0 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    read_at TIMESTAMP,
    CONSTRAINT fk_notification_user FOREIGN KEY (recipient_id) REFERENCES users(id)
);

CREATE TABLE audit_log (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100 CHAR),
    action VARCHAR2(100 CHAR),
    entity_type VARCHAR2(50 CHAR),
    entity_id NUMBER(19,0),
    old_value VARCHAR2(4000 CHAR),
    new_value VARCHAR2(4000 CHAR),
    ip_address VARCHAR2(50 CHAR),
    user_agent VARCHAR2(500 CHAR),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_bug_cr ON bug(cr_id);
CREATE INDEX idx_bug_status ON bug(status);
CREATE INDEX idx_bug_assigned ON bug(assigned_to);
CREATE INDEX idx_bug_severity ON bug(severity);
CREATE INDEX idx_bug_priority ON bug(priority);
CREATE INDEX idx_bug_reported_at ON bug(reported_at);
CREATE INDEX idx_bug_status_priority ON bug(status, priority);
CREATE INDEX idx_cr_status ON change_request(status);
CREATE INDEX idx_cr_project ON change_request(project_id);
CREATE INDEX idx_test_cycle_cr ON test_cycle(cr_id);
CREATE INDEX idx_test_case_cr ON test_case(cr_id);

