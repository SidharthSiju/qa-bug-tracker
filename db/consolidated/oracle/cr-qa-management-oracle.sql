-- ============================================================================================================
-- CR Issue Tracker - complete Oracle setup (schema + seed data)
--
-- The whole current schema and the seed data in one script, for a NEW Oracle environment. Existing environments keep
-- their Flyway history and are not affected by this file.
--
-- It is the Oracle migration chain (classpath:db/oracle, V1..V25) verbatim and in version order, so every statement
-- here is one Flyway has already run successfully. The one change: the CREATE SEQUENCE statements are moved to the
-- top of the file. The chain's seed inserts call those sequences but the chain only creates them in V14/V16/V17, so a
-- fresh database could never finish the chain (the same trap the PostgreSQL script has).
--
-- Usage (as the schema owner):
--     sqlplus mytelco/password@//host:1524/SERVICE @cr-qa-management-oracle.sql
--
-- Then let the application know the schema is already current, so Flyway does not replay the chain:
--     SPRING_FLYWAY_BASELINE_ON_MIGRATE=true SPRING_FLYWAY_BASELINE_VERSION=25
-- (or spring.flyway.baseline-on-migrate / baseline-version in application.yml). Flyway records the schema as being at
-- V25 and applies only migrations newer than that.
--
-- Oracle folds unquoted identifiers to upper case, so IT_USERS_SEQ and the application's
-- @SequenceGenerator(sequenceName = "IT_USERS_SEQ") agree: keep these names unquoted. The tables are created with
-- their pre-IT_ names and renamed by V13, exactly as the chain does.
--
-- Generated from the migration chain at 5389e01. Sequences hoisted above the first insert (V2__dml.sql).
-- ============================================================================================================

